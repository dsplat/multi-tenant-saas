        // 与 config('domain.wildcard_base') 同源（模块 config 合并晚于本文件加载，故直读 env）。
        // 边界：租户 approved 自定义域名仍需手工追加进 SANCTUM_STATEFUL_DOMAINS。
        env('PLATFORM_WILDCARD_BASE') ? ['*.'.env('PLATFORM_WILDCARD_BASE')] : [],
    )))),

    /*
    |--------------------------------------------------------------------------
    | Sanctum Guards
    |--------------------------------------------------------------------------
    |
